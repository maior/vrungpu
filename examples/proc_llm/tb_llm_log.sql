CREATE TABLE TB_LLM_LOG (
    LOG_SEQ     NUMBER          NOT NULL,
    REQ_DTM     DATE            DEFAULT SYSDATE NOT NULL,
    QUESTION    VARCHAR2(4000),
    ANSWER      VARCHAR2(4000),
    RC          NUMBER(3),
    CONSTRAINT PK_TB_LLM_LOG PRIMARY KEY (LOG_SEQ)
);
CREATE SEQUENCE SQ_LLM_LOG;
